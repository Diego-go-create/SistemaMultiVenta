  const originalText = new WeakMap();
  const originalAttributes = new WeakMap();

  window.applyGoStoreLanguage = (language) => {
    const catalog = catalogs[language] || {};
    const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT);
    let node;
    while ((node = walker.nextNode())) {
      const parent = node.parentElement;
      if (parent?.closest('.product-name, .product-category, .admin-product-info, .cart-item-info b, .notification-copy > span, .order-line, .review-card, .nav-user b, a[data-category-filter]:not([data-category-filter=""])')) continue;
      if (!originalText.has(node)) originalText.set(node, node.nodeValue);
      const original = originalText.get(node);
      const text = original.trim();
      const translation = Object.prototype.hasOwnProperty.call(catalog, text) ? catalog[text] : text;
      node.nodeValue = original.replace(text, translation);
    }

    document.querySelectorAll('[placeholder], [aria-label], [title]').forEach((element) => {
      if (!originalAttributes.has(element)) originalAttributes.set(element, new Map());
      ['placeholder', 'aria-label', 'title'].forEach((attribute) => {
        const attributes = originalAttributes.get(element);
        if (!attributes.has(attribute)) attributes.set(attribute, element.getAttribute(attribute));
        const value = attributes.get(attribute);
        if (value) {
          const translation = Object.prototype.hasOwnProperty.call(catalog, value) ? catalog[value] : value;
          element.setAttribute(attribute, translation);
        }
      });
    });
  };

  document.addEventListener('DOMContentLoaded', () => {
    window.applyGoStoreLanguage(document.body.dataset.lang || 'es');
  });
